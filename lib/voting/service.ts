export function buildVoteShareUrl(input: {
  communitySubdomain: string;
  categorySlug?: string | null;
}): string {
  const protocol = env.NEXT_PUBLIC_APP_URL.startsWith("https") ? "https" : "http";
  const origin = buildCommunityHostname(
    input.communitySubdomain,
    env.NEXT_PUBLIC_ROOT_DOMAIN,
    protocol,
  );
  if (input.categorySlug) {
    return `${origin}/vote/${input.categorySlug}`;
  }
  return `${origin}/vote`;
}

export async function getBusinessFinalistPresence(input: {
  businessId: string;
  campaignId: string;
}): Promise<{ presence: "none" | "finalist"; locationIds: string[]; finalistIds: string[] }> {
  const supabase = await createSupabaseServerClient();
  const { data: locations } = await supabase
    .from("business_locations")
    .select("id")
    .eq("business_id", input.businessId)
    .is("deleted_at", null);

  const locationIds = (locations ?? []).map((row) => row.id);
  if (!locationIds.length) {
    return { presence: "none", locationIds: [], finalistIds: [] };
  }

  const { data: finalists } = await supabase
    .from("finalists")
    .select("id")
    .eq("campaign_id", input.campaignId)
    .eq("status", "published")
    .in("business_location_id", locationIds);

  const finalistIds = (finalists ?? []).map((row) => row.id);
  return {
    presence: finalistIds.length ? "finalist" : "none",
    locationIds,
    finalistIds,
  };
}

