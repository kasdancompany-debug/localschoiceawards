async function recordVoteEvent(
  voteId: string,
  eventType: VoteEventType,
  metadata: Record<string, string | number | boolean | null> = {},
) {
  const admin = createSupabaseAdminClient();
  await admin.from("vote_events").insert({
    vote_id: voteId,
    event_type: eventType,
    metadata,
  });
}

async function countValidNominations(
  campaignId: string,
  campaignCategoryId: string,
  businessLocationId: string,
): Promise<number> {
  const admin = createSupabaseAdminClient();
  const { count } = await admin
    .from("nominations")
    .select("id", { count: "exact", head: true })
    .eq("campaign_id", campaignId)
    .eq("campaign_category_id", campaignCategoryId)
    .eq("business_location_id", businessLocationId)
    .eq("status", "valid");
  return count ?? 0;
}

export async function generateProposedFinalists(input: {
  campaignId: string;
  campaignCategoryId?: string | null;
  actorUserId: string;
}): Promise<{ ok: boolean; message: string; created: number }> {
  const admin = createSupabaseAdminClient();
  let categoryQuery = admin
    .from("campaign_categories")
    .select("*")
    .eq("campaign_id", input.campaignId)
    .eq("active", true);
  if (input.campaignCategoryId) {
    categoryQuery = categoryQuery.eq("id", input.campaignCategoryId);
  }
  const { data: categories } = await categoryQuery;
  if (!categories?.length) {
    return { ok: false, message: "No active categories found.", created: 0 };
  }

  let created = 0;
  for (const categoryRow of categories) {
    const category = mapCampaignCategory(categoryRow);
    const { data: nominations } = await admin
      .from("nominations")
      .select("business_location_id")
      .eq("campaign_id", input.campaignId)
      .eq("campaign_category_id", category.id)
      .eq("status", "valid")
      .not("business_location_id", "is", null);

    const counts = new Map<string, number>();
    for (const row of nominations ?? []) {
      if (!row.business_location_id) continue;
      counts.set(row.business_location_id, (counts.get(row.business_location_id) ?? 0) + 1);
    }

    const proposed = proposeFinalistsFromNominations(
      [...counts.entries()].map(([businessLocationId, validNominationCount]) => ({
        businessLocationId,
        validNominationCount,
      })),
      {
        finalistLimit: category.finalistLimit,
        minimumNominationCount: category.minimumNominationCount,
      },
    );

    // Soft-remove previous automatic proposals that are not in the new set.
    const keepIds = new Set(proposed.map((item) => item.businessLocationId));
    const { data: existing } = await admin
      .from("finalists")
      .select("*")
      .eq("campaign_id", input.campaignId)
      .eq("campaign_category_id", category.id)
      .in("status", ["proposed"]);

    for (const row of existing ?? []) {
      if (!keepIds.has(row.business_location_id) && row.selection_method === "automatic") {
        await admin
          .from("finalists")
          .update({
            status: "removed",
            removal_reason: "Replaced by regenerated automatic proposal",
            admin_notes: `Regenerated by ${input.actorUserId}`,
          })
          .eq("id", row.id);
      }
    }

    for (const candidate of proposed) {
      const { data: current } = await admin
        .from("finalists")
        .select("id, status")
        .eq("campaign_id", input.campaignId)
        .eq("campaign_category_id", category.id)
        .eq("business_location_id", candidate.businessLocationId)
        .in("status", ["proposed", "approved", "published"])
        .maybeSingle();

      if (current) {
        continue;
      }

      const { error } = await admin.from("finalists").insert({
        campaign_id: input.campaignId,
        campaign_category_id: category.id,
        business_location_id: candidate.businessLocationId,
        selection_method: "automatic",
        status: "proposed",
        selected_by: input.actorUserId,
        selected_at: new Date().toISOString(),
        admin_notes: "Generated from valid nominations",
      });
      if (!error) {
        created += 1;
      }
    }
  }

  return {
    ok: true,
    message: `Proposed ${created} finalist${created === 1 ? "" : "s"}.`,
    created,
  };
}

export async function approveFinalist(input: {
  finalistId: string;
  actorUserId: string;
}): Promise<{ ok: boolean; message: string }> {
  const admin = createSupabaseAdminClient();
  const { data: finalist } = await admin
    .from("finalists")
    .select("*")
    .eq("id", input.finalistId)
    .maybeSingle();
  if (!finalist || finalist.status === "removed") {
    return { ok: false, message: "Finalist not found." };
  }

  const snapshot = await countValidNominations(
    finalist.campaign_id,
    finalist.campaign_category_id,
    finalist.business_location_id,
  );

  const { error } = await admin
    .from("finalists")
    .update({
      status: "approved",
      nomination_count_snapshot: snapshot,
      selected_at: new Date().toISOString(),
      selected_by: input.actorUserId,
    })
    .eq("id", input.finalistId);

  return {
    ok: !error,
    message: error ? "Unable to approve finalist." : "Finalist approved with frozen nomination snapshot.",
  };
}

