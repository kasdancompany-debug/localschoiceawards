export async function listPublishedFinalists(input: {
  campaign: Campaign;
  communityId: string;
  categorySlug?: string;
}): Promise<PublicFinalistView[]> {
  const state = resolveCampaignState(input.campaign);
  if (!state.canPublicReadCampaign) {
    return [];
  }

  try {
    const supabase = await createSupabaseServerClient();
    const query = supabase
      .from("finalists")
      .select(
        `
        id,
        campaign_category_id,
        business_location_id,
        campaign_categories (
          local_name,
          local_slug,
          active,
          master_categories ( name, slug, category_groups ( name ) )
        ),
        business_locations!inner (
          location_name,
          community_id,
          slug,
          businesses!inner (
            public_name,
            slug,
            logo_url,
            status,
            deleted_at
          )
        )
      `,
      )
      .eq("campaign_id", input.campaign.id)
      .eq("status", "published")
      .eq("business_locations.community_id", input.communityId);

    const { data } = await query;
    if (!data) {
      return [];
    }

    return data.flatMap((row) => {
      const category = row.campaign_categories as unknown as {
        local_name: string | null;
        local_slug: string | null;
        active: boolean;
        master_categories: {
          name: string;
          slug: string;
          category_groups: { name: string } | null;
        } | null;
      } | null;
      const location = row.business_locations as unknown as {
        location_name: string;
        community_id: string;
        slug: string;
        businesses: {
          public_name: string;
          slug: string;
          logo_url: string | null;
          status: string;
          deleted_at: string | null;
        };
      };

      if (!category?.active || location.businesses.deleted_at || location.businesses.status !== "approved") {
        return [];
      }

      const categorySlug =
        category.local_slug || category.master_categories?.slug || "category";
      if (input.categorySlug && categorySlug !== input.categorySlug) {
        return [];
      }

      return [
        toPublicFinalistView({
          finalistId: row.id,
          categoryId: row.campaign_category_id,
          categoryName: category.local_name || category.master_categories?.name || "Category",
          categorySlug,
          groupName: category.master_categories?.category_groups?.name || "Categories",
          businessName: location.businesses.public_name,
          businessSlug: location.businesses.slug,
          locationName: location.location_name,
          logoUrl: location.businesses.logo_url,
        }),
      ];
    });
  } catch {
    return [];
  }
}

export type CastVoteResult =
  | { ok: true; voteId: string; changed: boolean }
  | { ok: false; reason: VoteRuleFailure | "rate_limited" | "server_error"; message: string };

export async function castOrChangeVote(input: {
  campaign: Campaign;
  communityId: string;
  userId: string;
  email: string;
  emailConfirmed: boolean;
  campaignCategoryId: string;
  finalistId: string;
  ipAddress?: string | null;
}): Promise<CastVoteResult> {
  const campaignState = resolveCampaignState(input.campaign);
  const admin = createSupabaseAdminClient();

  const { data: category } = await admin
    .from("campaign_categories")
    .select("id, campaign_id, active")
    .eq("id", input.campaignCategoryId)
    .eq("campaign_id", input.campaign.id)
    .maybeSingle();

  const { data: finalist } = await admin
    .from("finalists")
    .select(
      `
      id,
      campaign_id,
      campaign_category_id,
      status,
      business_location_id,
      business_locations ( community_id )
    `,
    )
    .eq("id", input.finalistId)
    .maybeSingle();

  const locationCommunityId = (
    finalist?.business_locations as unknown as { community_id: string } | null
  )?.community_id;

  const eligibility = evaluateVoteEligibility({
    emailConfirmed: input.emailConfirmed,
    campaignState,
    votingLocked: campaignState.votingLocked,
    categoryBelongsToCampaign: Boolean(category),
    categoryActive: Boolean(category?.active),
    finalistExists: Boolean(finalist),
    finalistPublished: finalist?.status === "published",
    finalistBelongsToCategory: finalist?.campaign_category_id === input.campaignCategoryId,
    finalistInCommunity: locationCommunityId === input.communityId,
  });

  if (!eligibility.ok) {
    const signalType =
      eligibility.reason === "unverified_user"
        ? "unverified_user"
        : eligibility.reason === "voting_closed" || eligibility.reason === "voting_locked"
          ? "closed_phase_attempt"
          : eligibility.reason === "cross_community"
            ? "cross_community_attempt"
            : "manual_review";

    await recordFraudSignal({
      campaignId: input.campaign.id,
      entityType: "user",
      entityId: input.userId,
      signalType,
      riskScore: 40,
      metadata: {
        reason: eligibility.reason,
        ipHash: input.ipAddress ? hashIpFingerprint(input.ipAddress) : null,
        finalistId: input.finalistId,
      },
    });

    return {
      ok: false,
      reason: eligibility.reason,
      message: voteRuleMessage(eligibility.reason),
    };
  }

  const { data: existing } = await admin
    .from("votes")
    .select("*")
    .eq("campaign_id", input.campaign.id)
    .eq("campaign_category_id", input.campaignCategoryId)
    .eq("user_id", input.userId)
    .eq("status", "active")
    .maybeSingle();

  if (existing) {
    if (existing.finalist_id === input.finalistId) {
      return { ok: true, voteId: existing.id, changed: false };
    }

    const { data: updated, error } = await admin
      .from("votes")
      .update({ finalist_id: input.finalistId })
      .eq("id", existing.id)
      .eq("status", "active")
      .select("*")
      .maybeSingle();

    if (error || !updated) {
      return { ok: false, reason: "server_error", message: "Unable to change vote." };
    }

    await recordVoteEvent(updated.id, "changed", {
      previousFinalistId: existing.finalist_id,
      nextFinalistId: input.finalistId,
    });

    return { ok: true, voteId: updated.id, changed: true };
  }

  const { data: created, error } = await admin
    .from("votes")
    .insert({
      campaign_id: input.campaign.id,
      campaign_category_id: input.campaignCategoryId,
      finalist_id: input.finalistId,
      user_id: input.userId,
      verified_email_hash: hashVerifiedEmail(input.email),
      status: "active",
    })
    .select("*")
    .maybeSingle();

  if (error || !created) {
    if (error?.code === "23505") {
      return {
        ok: false,
        reason: "server_error",
        message: "You already have an active vote in this category.",
      };
    }
    return { ok: false, reason: "server_error", message: "Unable to save vote." };
  }

  await recordVoteEvent(created.id, "created", { finalistId: input.finalistId });
  return { ok: true, voteId: created.id, changed: false };
}

export async function invalidateVote(input: {
  voteId: string;
  actorUserId: string;
  reason: string;
}): Promise<{ ok: boolean; message: string }> {
  const admin = createSupabaseAdminClient();
  const { data, error } = await admin
    .from("votes")
    .update({
      status: "invalidated",
      invalidated_at: new Date().toISOString(),
      invalidated_by: input.actorUserId,
      invalidation_reason: input.reason,
    })
    .eq("id", input.voteId)
    .eq("status", "active")
    .select("*")
    .maybeSingle();

  if (error || !data) {
    return { ok: false, message: "Unable to invalidate vote." };
  }

  await recordVoteEvent(data.id, "invalidated", {
    reason: input.reason,
    actorUserId: input.actorUserId,
  });

  await recordFraudSignal({
    campaignId: data.campaign_id,
    entityType: "vote",
    entityId: data.id,
    signalType: "manual_review",
    riskScore: 60,
    metadata: { reason: input.reason },
  });

  return { ok: true, message: "Vote invalidated." };
}

export async function lockVoting(input: {
  campaignId: string;
  lock: boolean;
}): Promise<{ ok: boolean; message: string }> {
  const admin = createSupabaseAdminClient();
  const { error } = await admin
    .from("campaigns")
    .update({
      voting_locked_at: input.lock ? new Date().toISOString() : null,
      status: input.lock ? "voting_closed" : "voting_open",
    })
    .eq("id", input.campaignId);

  return {
    ok: !error,
    message: error
      ? "Unable to update voting lock."
      : input.lock
        ? "Voting locked."
        : "Voting unlocked.",
  };
}

