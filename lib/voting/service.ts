export async function getVotingActivity(campaignId: string): Promise<
  Array<{ campaignCategoryId: string; activeVotes: number; invalidatedVotes: number }>
> {
  const admin = createSupabaseAdminClient();
  const { data } = await admin
    .from("votes")
    .select("campaign_category_id, status")
    .eq("campaign_id", campaignId);

  const map = new Map<
    string,
    { campaignCategoryId: string; activeVotes: number; invalidatedVotes: number }
  >();

  for (const row of data ?? []) {
    const current = map.get(row.campaign_category_id) ?? {
      campaignCategoryId: row.campaign_category_id,
      activeVotes: 0,
      invalidatedVotes: 0,
    };
    if (row.status === "active") current.activeVotes += 1;
    if (row.status === "invalidated") current.invalidatedVotes += 1;
    map.set(row.campaign_category_id, current);
  }

  return [...map.values()];
}

export async function buildVotingAuditReport(campaignId: string): Promise<string> {
  const [finalists, votes, activity] = await Promise.all([
    listAdminFinalists(campaignId),
    listAdminVotes(campaignId),
    getVotingActivity(campaignId),
  ]);

  const lines = [
    `Voting audit report for campaign ${campaignId}`,
    `Generated at ${new Date().toISOString()}`,
    "",
    `Finalists: ${finalists.length}`,
    `  proposed=${finalists.filter((f) => f.status === "proposed").length}`,
    `  approved=${finalists.filter((f) => f.status === "approved").length}`,
    `  published=${finalists.filter((f) => f.status === "published").length}`,
    `  removed=${finalists.filter((f) => f.status === "removed").length}`,
    "",
    `Votes: ${votes.length}`,
    `  active=${votes.filter((v) => v.status === "active").length}`,
    `  invalidated=${votes.filter((v) => v.status === "invalidated").length}`,
    "",
    "Category activity:",
    ...activity.map(
      (row) =>
        `  ${row.campaignCategoryId}: active=${row.activeVotes} invalidated=${row.invalidatedVotes}`,
    ),
    "",
    "Note: Exact public vote totals must remain hidden until results are published.",
  ];

  return lines.join("\n");
}
